import{z}from"zod";
export const UserSchema=z.object({
    name: z
    .string()
    .min(3, { message: "الاسم يجب ألا يقل عن 3 أحرف." })
    .regex(/^[A-Z][a-zA-Z\s]*$/, { 
      message: "يجب أن يبدأ الاسم بحرف كبير (Capital Letter)." 
    }),

  // 2. التحقق من البريد الإلكتروني (Zod يوفر فحص جاهز وصحيح للإيميل)
  email: z
    .string()
    .email({ message: "صيغة البريد الإلكتروني غير صحيحة." }),

  // 3. التحقق من كلمة المرور (شروط قوية: حرف كابيتال، سمول، أرقام، ورموز)
  password: z
    .string()
    .min(8, { message: "كلمة المرور يجب ألا تقل عن 8 أحرف." })
    .regex(/[A-Z]/, { message: "يجب أن تحتوي كلمة المرور على حرف كبير واحد على الأقل." })
    .regex(/[a-z]/, { message: "يجب أن تحتوي كلمة المرور على حرف صغير واحد على الأقل." })
    .regex(/[0-9]/, { message: "يجب أن تحتوي كلمة المرور على رقم واحد على الأقل." })
    .regex(/[^A-Za-z0-9]/, { message: "يجب أن تحتوي كلمة المرور على رمز خاص واحد على الأقل (مثل @, #, $)." }),
});